'use strict';
const {createHash,randomBytes}=require('node:crypto');
const admin=require('/tmp/vcp-reset/node_modules/firebase-admin');
const slug='vcp-resume-815b82f2047852dc5a96e5649af51217';
(async()=>{
 const raw=process.env.FIREBASE_SERVICE_ACCOUNT;
 if(!raw)throw new Error('Account maintenance credential is unavailable.');
 const credentials=JSON.parse(raw.trim().startsWith('{')?raw:Buffer.from(raw,'base64').toString());
 if(credentials.project_id!=='veteran-career-builder')throw new Error('Wrong Firebase project.');
 if(credentials.private_key?.includes('\\n'))credentials.private_key=credentials.private_key.replace(/\\n/g,'\n');
 admin.initializeApp({credential:admin.credential.cert(credentials),projectId:credentials.project_id});
 const db=admin.firestore(),cv=await db.collection('publicProfiles').doc(slug).get();
 if(!cv.exists||cv.data().source!=='vcp-resume-program')throw new Error('The specified app CV is unavailable. No data was changed.');
 const uid=cv.data().uid;
 if(typeof uid!=='string'||'vcp-resume-'+createHash('sha256').update('vcp-resume-program:'+uid).digest('hex').slice(0,32)!==slug)throw new Error('Public CV identity does not match. No data was changed.');
 const user=await admin.auth().getUser(uid);
 if(!user.email)throw new Error('The CV owner has no account email. No data was changed.');
 const challenge=randomBytes(32).toString('hex');
 const library=await db.collection('profiles').doc(uid).collection('resumeProgramResumes').get();
 const builds=await db.collection('_privateResumeProgramUsers').doc(uid).collection('builds').get();
 console.log(JSON.stringify({mode:'inspect-only',uid,challenge,identityDigest:createHash('sha256').update(challenge+':'+user.email.trim().toLowerCase()).digest('hex'),savedResumes:library.size,builds:builds.size,publicCv:true}));
 await admin.app().delete();
})().catch(error=>{console.error('Account inspection failed. No data was changed. Code: '+(error.code||error.message));process.exitCode=1;});
